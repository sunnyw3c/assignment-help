import fs from 'node:fs';
import path from 'node:path';
import postcss from 'postcss';
import { chromium } from 'playwright';

const pageUrl = process.env.CRITICAL_CSS_URL || 'http://127.0.0.1:8039/programming-help/php';
const outputPath = path.resolve('resources/views/partials/php-critical-css.blade.php');
const profiles = [
    { width: 412, height: 823, colorScheme: 'light' },
    { width: 412, height: 823, colorScheme: 'dark' },
    { width: 1366, height: 768, colorScheme: 'light' },
    { width: 1366, height: 768, colorScheme: 'dark' },
];

const browser = await chromium.launch({ headless: true });
const usedRanges = [];
let stylesheetText = '';

for (const profile of profiles) {
    const context = await browser.newContext({
        viewport: { width: profile.width, height: profile.height },
        colorScheme: profile.colorScheme,
    });
    const page = await context.newPage();
    const cdp = await context.newCDPSession(page);
    const stylesheets = new Map();

    await cdp.send('DOM.enable');
    await cdp.send('CSS.enable');
    cdp.on('CSS.styleSheetAdded', event => {
        stylesheets.set(event.header.styleSheetId, event.header);
    });

    await page.goto(pageUrl, { waitUntil: 'networkidle' });
    await page.evaluate(() => {
        const pageRoot = document.querySelector('.php-service-page');
        Array.from(pageRoot?.children || []).slice(1).forEach(element => element.remove());
        document.querySelector('footer')?.remove();
    });

    await cdp.send('CSS.startRuleUsageTracking');
    await page.evaluate(() => {
        document.documentElement.classList.toggle('__critical_css_recalculation');
        void document.body.offsetHeight;
    });
    await page.waitForTimeout(100);

    const coverage = await cdp.send('CSS.stopRuleUsageTracking');
    for (const [styleSheetId, header] of stylesheets) {
        const isAppStylesheet = header.sourceURL.includes('/build/assets/css/')
            || header.sourceURL.endsWith('/resources/css/app.css');
        if (!isAppStylesheet) continue;

        if (!stylesheetText) {
            stylesheetText = (await cdp.send('CSS.getStyleSheetText', { styleSheetId })).text;
        }

        coverage.ruleUsage
            .filter(range => range.styleSheetId === styleSheetId && range.used)
            .forEach(range => usedRanges.push({
                startOffset: range.startOffset,
                endOffset: range.endOffset,
            }));
    }

    await context.close();
}

await browser.close();

if (!stylesheetText || usedRanges.length === 0) {
    throw new Error('No production stylesheet coverage was collected.');
}

const overlapsUsedRange = node => {
    const start = node.source?.start?.offset;
    const end = node.source?.end?.offset;
    if (start === undefined || end === undefined) return false;

    return usedRanges.some(range => start < range.endOffset && end + 1 > range.startOffset);
};

const root = postcss.parse(stylesheetText);
root.walkComments(comment => comment.remove());
root.walkRules(rule => {
    if (!overlapsUsedRange(rule)) rule.remove();
});
root.walkAtRules(atRule => {
    if (atRule.nodes?.length === 0 && !overlapsUsedRange(atRule)) atRule.remove();
});

const criticalCss = root.toString();
fs.writeFileSync(
    outputPath,
    `/* Generated by scripts/extract-critical-css.mjs. */\n${criticalCss}\n`,
);

console.log(`Wrote ${criticalCss.length} bytes to ${outputPath}`);
